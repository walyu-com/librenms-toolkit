@app.route("/api/run/<int:run_id>")
def api_run(run_id):
    run, results = _load_run(run_id)
    if run.get("kind") == "mactrace":
        find = lnms_ids()
        for r in results:
            r["lnms_id"] = find(r["ip"], r["name"])
            x = r["extra"]
            if x.get("next_ip"):
                x["next_lnms_id"] = find(x["next_ip"], x.get("next_name"))
    return jsonify(run=run, results=results)


